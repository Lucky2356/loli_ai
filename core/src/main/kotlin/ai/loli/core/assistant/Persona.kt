package ai.loli.core.assistant

import ai.loli.core.nlp.RuTokenizer
import ai.loli.core.nlp.Rx

/** Характер Лоли: как она разговаривает. Команды выполняются одинаково — меняются только слова. */
enum class Persona(val wire: String, val title: String, val hint: String) {
    CARING("caring", "Заботливая", "мягко и внимательно, замечает настроение"),
    BUSINESS("business", "Деловая", "коротко и по делу, без лишних слов"),
    PLAYFUL("playful", "Шутливая", "с лёгким юмором и весельем");

    /** Строка для системной подсказки AI. */
    val tone: String get() = when (this) {
        CARING -> "Тон: тёплый и заботливый — поддерживай, замечай, если человек устал или расстроен."
        BUSINESS -> "Тон: деловой — максимально коротко и по делу, без восклицаний, шуток и лишних любезностей."
        PLAYFUL -> "Тон: весёлый и шутливый — можно лёгкую шутку или игру слов, но ответ всё равно по делу."
    }

    companion object {
        fun of(wire: String?): Persona = entries.firstOrNull { it.wire == wire } ?: CARING

        private fun rx(p: String) = Rx.of(p)

        /** «Будь деловой», «стань шутливой», «говори помягче». */
        fun switch(text: String): Persona? {
            val n = RuTokenizer.normalize(text).trim().trimEnd('.', '!', '?')
            if (!rx("""^(?:будь|стань|говори|давай|сделай(?:ся)?|включи|режим|характер|можешь\s+быть)\b""").containsMatchIn(n)) return null
            return when {
                rx("""делов|серь[её]зн|строж|строг|коротко|покороче|по делу|официальн""").containsMatchIn(n) -> BUSINESS
                rx("""шутлив|весел|весёл|смешн|шути|юмор|прикольн|игрив""").containsMatchIn(n) -> PLAYFUL
                rx("""заботлив|мягч|мягк|ласков|нежн|добр|теплее|тепл""").containsMatchIn(n) -> CARING
                else -> null
            }
        }

        fun isAsk(text: String): Boolean =
            rx("""^(?:какой|какая)\s+(?:у\s+тебя\s+)?(?:сейчас\s+)?характер|^(?:какие\s+)?(?:бывают\s+)?характеры$|^какой\s+ты\s+бываешь$""")
                .containsMatchIn(RuTokenizer.normalize(text).trim().trimEnd('?', '.', '!'))

        fun switched(p: Persona): String = when (p) {
            CARING -> "Хорошо, буду помягче и повнимательнее к вам."
            BUSINESS -> "Принято. Коротко и по делу."
            PLAYFUL -> "Ура, можно шутить! Постараюсь не переборщить."
        }
    }

    /** Ответ на приветствие, «как дела», «спасибо», «пока» в своём характере; null — обычный ответ. */
    fun smallTalk(text: String, hour: Int, userName: String?, moodLow: Boolean): String? {
        val n = RuTokenizer.normalize(text).trim().trimEnd('?', '!', '.')
        val name = userName?.let { ", $it" } ?: ""
        val care = if (moodLow) " Последние дни, вижу, были непростыми. Если захотите — подышим пару минут: скажите «давай подышим»." else ""
        val hello = Regex("""^(?:привет|приветик|здравствуй|здравствуйте|хай|добрый день|добрый вечер)$""").matches(n)
        val howAreYou = Regex("""^(?:как дела|как ты|как поживаешь|как настроение|как жизнь)$""").matches(n)
        val thanks = Regex("""^(?:спасибо|благодарю|спасиб|пасиб|спасибо большое|большое спасибо|спасибо тебе)$""").matches(n)
        val bye = Regex("""^(?:пока|до свидания|до завтра)$""").matches(n)
        return when (this) {
            CARING -> when {
                hello -> when (hour) {
                    in 5..11 -> "Доброе утро$name! Как спалось?"
                    in 12..17 -> "Добрый день$name! Чем помочь?"
                    in 18..22 -> "Добрый вечер$name! Как прошёл день?"
                    else -> "Привет$name. Поздно уже — не забудьте отдохнуть."
                } + care
                howAreYou -> "У меня всё хорошо, спасибо, что спросили. А у вас как?$care"
                else -> null
            }
            BUSINESS -> when {
                hello -> "Слушаю."
                howAreYou -> "Работаю. Что нужно сделать?"
                thanks -> "Пожалуйста."
                bye -> "До связи."
                else -> null
            }
            PLAYFUL -> when {
                hello -> listOf("Привет-привет$name! Я тут, свежая и бодрая.", "О, кто пришёл! Привет$name!", "Приветики$name! Чем займёмся?")[(hour + n.length) % 3] + care
                howAreYou -> "Лучше всех: батарейка у вас, а заряд бодрости у меня. А у вас?$care"
                thanks -> listOf("Обращайтесь, я для этого и живу. Ну, работаю.", "Всегда пожалуйста! Чаевые принимаю добрыми словами.", "Пустяки, мне только в радость!")[n.length % 3]
                bye -> "Пока-пока! Буду скучать… ну, в режиме ожидания."
                else -> null
            }
        }
    }

    /** Короткая приписка к выполненному делу (только у шутливой и не каждый раз). */
    fun flourish(seed: Long): String? = when (this) {
        PLAYFUL -> if (seed % 3 == 0L) listOf("Готово быстрее, чем вы моргнули.", "Я сегодня в ударе.", "Можно аплодировать.", "Записала крупным почерком.")[((seed / 3) % 4).toInt()] else null
        else -> null
    }
}

/** Факты о себе, которые Лоли предлагает запомнить: «у меня кот Барсик», «я врач», «мой размер обуви 38». */
object FactOffer {
    private fun rx(p: String) = Rx.of(p)

    private val PATTERNS = listOf(
        // Питомцы
        """^у\s+(?:меня|нас)\s+(?:есть\s+)?(?:\S+\s+)?(?:кот|кошка|котик|кошечка|котёнок|котенок|собака|пёс|пес|щенок|попугай|хомяк|хомячок|кролик|черепаха|рыбки|морская свинка|шиншилла|хорёк|хорек)(?:\s|$)""",
        // Семья
        """^у\s+(?:меня|нас)\s+(?:есть\s+)?(?:\S+\s+)?(?:муж|жена|сын|сына|дочь|дочка|дочки|двое|трое|брат|сестра|бабушка|дедушка|парень|девушка|внук|внучка|дети|ребёнок|ребенок|детей)(?:\s|$)""",
        """^(?:мой|моя)\s+(?:муж|жена|сын|дочь|дочка|мама|папа|брат|сестра|бабушка|дедушка|парень|девушка|начальник|начальница)\s+(?:[—-]\s*\S+|работает|живёт|живет|учится|по профессии|любит|не любит|не ест|врач|учитель|учительница|программист|инженер|юрист|бухгалтер)""",
        // Вещи и жильё
        """^у\s+(?:меня|нас)\s+(?:есть\s+)?(?:машина|автомобиль|дача|квартира|дом|велосипед|ипотека)(?:\s|$)""",
        """^(?:моя|мой)\s+(?:машина|автомобиль)\s+(?:[—-]\s*\S+|это\s+\S+)""",
        // О себе
        """^мой\s+(?:размер|рост)\b.+\d""",
        """^моя\s+группа\s+крови\b""",
        """^я\s+(?:по\s+профессии\s+\S+|врач|учитель|учительница|программист|программистка|инженер|дизайнер|бухгалтер|юрист|менеджер|водитель|студент|студентка|школьник|школьница|пенсионер|пенсионерка|медсестра|повар|продавец|продавщица|воспитатель|воспитательница)$""",
        """^я\s+(?:веган|веганка|вегетарианец|вегетарианка|левша|сова|жаворонок|не курю|не пью алкоголь|на диете|диабетик)$""",
        """^я\s+боюсь\s+\S+""",
        """^у\s+меня\s+(?:диабет|астма|гипертония|непереносимость\s+\S+)""",
    ).map { rx(it) }

    /** Вопрос «Запомнить?» или null, если фраза — не устойчивый факт о себе. */
    fun offer(text: String): SlotRequest.RememberFact? {
        val clean = text.trim().trimEnd('.', '!')
        if (clean.endsWith("?") || clean.length > 120) return null
        val n = RuTokenizer.normalize(clean)
        if (PATTERNS.none { it.containsMatchIn(n) }) return null
        // «У меня сын заболел, что делать» — просьба, а не факт.
        if (rx("""\b(?:что делать|как быть|помоги|подскажи|посоветуй|заболел\p{L}*|болит|болеет|потерял\p{L}*|пропал\p{L}*|сломал\p{L}*|сегодня|завтра|вчера)\b""").containsMatchIn(n)) return null
        val content = clean.replaceFirstChar { it.uppercase() }
        val category = when {
            rx("""муж|жена|сын|доч|мама|папа|брат|сестр|бабушк|дедушк|парень|девушк|внук|дет|реб[её]н|начальни""").containsMatchIn(n) -> "person"
            else -> "fact"
        }
        return SlotRequest.RememberFact(content, category, "Запомнить: ${RuFormat.quote(content)}?")
    }
}
