package ai.loli.core.nlp

/**
 * Офлайн-«семантика»: группы близких по смыслу слов. Поиск по «приложениям для еды»
 * находит идею про холодильник, а «поездка» — заметку про отпуск, даже без AI и эмбеддингов.
 * Сравнение идёт по основам слов, поэтому формы («поездки», «поездку») учитываются автоматически.
 */
object Synonyms {
    private val groups: List<List<String>> = listOf(
        listOf("еда", "продукты", "холодильник", "кухня", "готовка", "рецепт", "блюдо", "ужин", "обед", "завтрак", "покупки", "магазин", "супермаркет"),
        listOf("отпуск", "путешествие", "поездка", "отдых", "тур", "билеты", "отель", "каникулы", "страна", "море", "перелет"),
        listOf("работа", "офис", "клиент", "проект", "встреча", "созвон", "коллега", "начальник", "дедлайн", "отчет"),
        listOf("здоровье", "врач", "больница", "клиника", "лекарство", "таблетки", "аптека", "анализы", "болезнь", "стоматолог"),
        listOf("деньги", "финансы", "бюджет", "расходы", "траты", "зарплата", "накопления", "кредит", "долг"),
        listOf("машина", "авто", "автомобиль", "автосервис", "шины", "бензин", "техосмотр", "парковка"),
        listOf("дом", "квартира", "ремонт", "мебель", "интерьер", "уборка", "переезд", "дача"),
        listOf("подарок", "день рождения", "праздник", "сюрприз", "поздравление", "юбилей", "годовщина", "свадьба"),
        listOf("учеба", "курс", "обучение", "книга", "урок", "экзамен", "университет", "школа", "лекция"),
        listOf("спорт", "тренировка", "зал", "фитнес", "бег", "йога", "бассейн", "упражнения"),
        listOf("приложение", "программа", "сервис", "сайт", "бот", "стартап", "проект", "продукт", "app"),
        listOf("список покупок", "покупки", "купить", "магазин", "продукты"),
        listOf("семья", "мама", "папа", "родители", "дети", "ребенок", "сын", "дочь", "брат", "сестра", "муж", "жена"),
        listOf("кино", "фильм", "сериал", "мультфильм", "смотреть"),
        listOf("музыка", "песня", "концерт", "плейлист", "альбом"),
        listOf("питомец", "кот", "кошка", "собака", "корм", "ветеринар"),
        listOf("идея", "мысль", "задумка", "придумка", "концепция"),
        listOf("склад", "остатки", "инвентарь", "учет", "товары", "штрихкод"),
    )

    private val stemGroups: List<Set<String>> by lazy { groups.map { g -> g.flatMap { TextAnalysis.stems(it) }.toSet() } }

    /** Близкие по смыслу слова (основы) для слов запроса, без самих слов запроса. */
    fun expand(query: String): List<String> {
        val q = TextAnalysis.stems(query).toSet()
        if (q.isEmpty()) return emptyList()
        return stemGroups.filter { g -> q.any { s -> g.any { TextAnalysis.stemSimilarity(s, it) >= 0.85 } } }
            .flatten().filter { it !in q }.distinct()
    }
}
