package ai.loli.core.nlp

/**
 * Разговорная речь → обычные слова, до всех разборщиков: «чё там по погоде» → «что там по погоде»,
 * «скока щас времени» → «сколько сейчас времени», «подскажи-ка, какой курс» → «какой курс».
 * Меняем только слова, которые почти всегда значат одно и то же.
 */
object Slang {
    private val WORDS: List<Pair<Regex, String>> = listOf(
        "чё|че|чо|шо|чë" to "что",
        "щас|щя|ща|счас|щаc" to "сейчас",
        "скока|скоко|скок|скольк" to "сколько",
        "седня|сёдня|седни|сёдни|сення|сёння|сегодн" to "сегодня",
        "завтро" to "завтра",
        "плиз|плз|пж|пжл|пжлст|пжлста|пожалста|пожалуста|пожалйста|пожалуйсто" to "пожалуйста",
        "спс|пасиб|пасибки|спасиб|спасибки|сенкс|сенкью" to "спасибо",
        "ваще|вааще|воще" to "вообще",
        "вобщем|вообщем" to "в общем",
        "мб" to "может быть",
        "чтоль|штоль|што ли" to "что ли",
        "нету" to "нет",
        "инет|интернеты" to "интернет",
        "тя" to "тебя",
        "прив|приветик|приветики|приветос|здрасте|здрасьте|здрасти|здорово бывала?" to "привет",
        "кароч|карочь|короч" to "короче",
        "оч" to "очень",
        "ща-ща" to "сейчас",
        "тыщ|тыщи|тыщу|тыща" to "тысяч",
        "будильничек" to "будильник",
        "таймерок" to "таймер",
        "напоминалку|напоминалка|напоминалочку" to "напоминание",
        "заметочку|заметочка" to "заметку",
        "погодку|погодка|погодочка|погодочку" to "погоду",
        "музычку|музыку-то|музон|музло" to "музыку",
        "фоточку|фотку|фотка" to "фото",
        "смску|смс-ку|эсэмэску|смсочку|смс-ку" to "смс",
        "телефончик" to "телефон",
        "новостишки|новостюшки" to "новости",
    ).map { (from, to) -> Regex("""(?iu)(?<![\p{L}\-])(?:$from)(?![\p{L}\-])""") to to }

    /** «скажи-ка», «дай-ка», «глянь-ка» — частица «-ка» не меняет смысла. */
    private val KA = Regex("""(?iu)(?<![\p{L}])(скажи|подскажи|дай|глянь|посмотри|напомни|включи|поставь|запиши|расскажи|покажи|найди|открой|давай|ну|а ну)-ка(?![\p{L}])""")

    /** Вводные обращения перед вопросом: «слушай, подскажи, а какая погода» → «какая погода». */
    private val LEAD = Regex(
        """(?iu)^(?:(?:слушай|послушай|скажи|скажите|подскажи|подскажите|а скажи|а подскажи|будь добра|будь другом|пожалуйста|ну|эй|короче|так|кстати|а|извини|извините|хочу узнать|мне интересно|интересно|не подскажешь|не подскажете|не знаешь|ты не знаешь|ты знаешь)[,\s]+)+(?=(?:а\s+)?(?:какая|какой|какие|какое|сколько|когда|где|что|кто|почему|зачем|как|есть ли|будет ли|будет|курс|погода|погоду|новости|почем|почём)(?![\p{L}]))""",
    )

    fun normalize(text: String): String {
        var t = text.trim()
        if (t.isEmpty()) return t
        for ((re, to) in WORDS) t = re.replace(t, to)
        t = KA.replace(t, "$1")
        t = LEAD.replace(t, "")
        return t.replace(Regex("""\s{2,}"""), " ").trim()
    }
}
