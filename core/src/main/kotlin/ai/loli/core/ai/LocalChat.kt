package ai.loli.core.ai

/**
 * Офлайн-модель на телефоне (llama.cpp): отвечает на свободные вопросы без интернета и ключей.
 * Команды (записать, напомнить…) она не выполняет — только разговор, советы, объяснения, тексты.
 */
interface LocalChat {
    /** Модель скачана и может отвечать. */
    val available: Boolean

    /** Ответ на реплику с учётом недавнего разговора; null — не получилось. */
    suspend fun reply(system: String, history: List<ChatMessage>, maxTokens: Int = 320): String?

    companion object {
        /** Реплика — вопрос или просьба к собеседнику, а не команда и не заметка. */
        fun looksLikeChat(text: String): Boolean {
            val t = text.trim().lowercase().replace('ё', 'е')
            if (t.endsWith("?")) return true
            return Regex(
                """^(?:а\s+|и\s+|слушай[,]?\s+|скажи[,]?\s+)?(?:почему|зачем|как|что|кто|где|когда|сколько|какой|какая|какое|какие|каким|чем|откуда|куда|чей|можно ли|стоит ли|правда ли|нужно ли|надо ли|расскажи|объясни|посоветуй|придумай|напиши|сочини|помоги|подскажи|переведи|поговори|давай поговорим|давай обсудим|как думаешь|что думаешь|ты знаешь|ты умеешь|ты любишь|ты можешь|кто лучше|что лучше|в чем разница)(?:\s|$)""",
            ).containsMatchIn(t) || Regex("""(?:^|\s)ли(?:\s|$)""").containsMatchIn(t)
        }

        fun systemPrompt(assistantName: String, userName: String?): String =
            "Ты — $assistantName, дружелюбный голосовой ассистент. Отвечай по-русски, от женского лица, коротко: 1–3 предложения, " +
                "без списков и разметки — ответ будет озвучен. Если не знаешь точно — так и скажи. " +
                (userName?.let { "Собеседника зовут $it. " } ?: "") +
                "Ты не можешь сама ставить напоминания или менять записи — если просят, подскажи, как сказать команду (например: «напомни завтра в 9 …»)."
    }
}
