    fun find(query: String?): Tale? {
        val q = query?.lowercase()?.replace('ё', 'е')?.trim().orEmpty()
        if (q.isEmpty()) return null
        return ALL.firstOrNull { t -> t.keys.any { q.contains(it.replace('ё', 'е')) } }
    }

    fun random(except: String? = null, random: Random = Random.Default): Tale = ALL.filter { it.title != except }.random(random)

    /** «Расскажи сказку», «сказку про колобка», «сказку на ночь», «придумай сказку про кота». */
    data class Request(val about: String?, val invent: Boolean)

    fun parse(text: String): Request? {
        val t = text.lowercase().replace('ё', 'е').trim().trimEnd('.', '!', '?')
        val m = Regex("""^(?:(?:расскажи|почитай|прочитай|давай|хочу|рассказывай|включи)\s+)?(?:(?:мне|нам|ребенку|детям|сыну|дочке)\s+)?(придумай\s+|сочини\s+)?сказк[ауи](?:\s+на ночь)?(?:\s+(?:про|о|об)\s+(.+))?$""").find(t)
            ?: Regex("""^(придумай|сочини)\s+(?:мне\s+)?сказку\s+(?:про|о|об)\s+(.+)$""").find(t)?.let { r -> return Request(r.groupValues[2], true) }
            ?: return null
        val invent = m.groupValues[1].isNotBlank()
        val about = m.groupValues[2].takeIf { it.isNotBlank() }
        return Request(about, invent)
    }
