    /** Православная Пасха (григорианская дата) — алгоритм для 1900–2099. */
    fun easter(year: Int): LocalDate {
        val a = year % 4; val b = year % 7; val c = year % 19
        val d = (19 * c + 15) % 30
        val e = (2 * a + 4 * b - d + 34) % 7
        val month = (d + e + 114) / 31
        val day = (d + e + 114) % 31 + 1
        return LocalDate.of(year, month, day).plusDays(13)
    }

    private fun nth(year: Int, month: Int, dow: DayOfWeek, n: Int) = LocalDate.of(year, month, 1).with(TemporalAdjusters.dayOfWeekInMonth(n, dow))
    private fun last(year: Int, month: Int, dow: DayOfWeek) = LocalDate.of(year, month, 1).with(TemporalAdjusters.lastInMonth(dow))

    /** Праздники с плавающей датой в этом году. */
    fun movable(year: Int): Map<LocalDate, List<String>> {
        val e = easter(year)
        val out = linkedMapOf<LocalDate, MutableList<String>>()
        fun add(d: LocalDate, name: String) { out.getOrPut(d) { mutableListOf() } += name }
        add(e, "Пасха")
        add(e.minusDays(7), "Вербное воскресенье")
        add(e.minusDays(49), "Прощёное воскресенье")
        for (i in 0..6) add(e.minusDays(55L - i), if (i == 0) "Начало Масленицы" else "Масленица")
        add(e.plusDays(39), "Вознесение Господне")
        add(e.plusDays(49), "Троица")
        add(LocalDate.ofYearDay(year, 256), "День программиста")
        add(nth(year, 6, DayOfWeek.SUNDAY, 3), "День медицинского работника")
        add(last(year, 7, DayOfWeek.SUNDAY), "День Военно-морского флота")
        add(nth(year, 7, DayOfWeek.SUNDAY, 3), "День металлурга")
        add(nth(year, 8, DayOfWeek.SUNDAY, 2), "День строителя")
        add(nth(year, 8, DayOfWeek.SATURDAY, 2), "День физкультурника")
        add(last(year, 8, DayOfWeek.SUNDAY), "День шахтёра")
        add(nth(year, 10, DayOfWeek.SUNDAY, 3), "День отца")
        add(last(year, 11, DayOfWeek.SUNDAY), "День матери")
        return out
    }

    fun holidays(date: LocalDate): List<String> = FIXED[MonthDay.from(date)].orEmpty() + movable(date.year)[date].orEmpty()

    /** Ближайший праздник после [from] (не включая). */
    fun nextHoliday(from: LocalDate): Pair<LocalDate, List<String>> {
        var d = from.plusDays(1)
        repeat(400) {
            val h = holidays(d)
            if (h.isNotEmpty()) return d to h
            d = d.plusDays(1)
        }
        return from to emptyList()
    }

    /** Дата праздника по названию: «Пасха», «Масленица», «День матери» — ближайшая с [from]. */
    fun find(name: String, from: LocalDate): LocalDate? = findTitled(name, from)?.first

    /** Ближайшая дата и точное название праздника; из похожих — где меньше лишних слов («День матери», а не «…и матери их Софии»). */
    fun findTitled(name: String, from: LocalDate): Pair<LocalDate, String>? {
        val qw = words(name)
        if (qw.isEmpty()) return null
        for (y in listOf(from.year, from.year + 1)) {
            val all = FIXED.flatMap { (md, names) -> names.map { md.atYear(y) to it } } + movable(y).flatMap { (d, names) -> names.map { d to it } }
            all.filter { (d, n) -> !d.isBefore(from) && !n.startsWith("Канун") && !n.startsWith("Первый день") && words(n).containsAll(qw) }
                .minWithOrNull(compareBy({ words(it.second).size - qw.size }, { it.first }))?.let { return it }
        }
        return null
    }

    /** Основы значимых слов: «пасхи» ~ «пасха», «победы» ~ «Победы». */
    private fun words(s: String): List<String> = s.lowercase().replace('ё', 'е').split(' ', '-', ',', '«', '»')
        .filter { it.length > 3 }.map { it.take(maxOf(4, it.length - 2)) }

