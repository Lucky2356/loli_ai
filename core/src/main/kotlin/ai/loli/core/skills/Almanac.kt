    /** Когда именины у имени (ближайшие даты). */
    fun nameDays(name: String): List<MonthDay> {
        val q = name.lowercase().replace('ё', 'е').take(4)
        return NAME_DAYS.filter { (_, names) -> names.any { it.lowercase().replace('ё', 'е').startsWith(q) } }.keys.sorted()
    }

