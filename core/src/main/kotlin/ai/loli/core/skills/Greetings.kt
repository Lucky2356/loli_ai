/** Готовые поздравления, если AI не подключён. */
object Greetings {
    private val BIRTHDAY = listOf(
        "С днём рождения! Пусть этот год принесёт много радости, здоровья и поводов улыбаться. Обнимаю!",
        "Поздравляю с днём рождения! Желаю, чтобы мечты сбывались, а рядом всегда были любимые люди.",
        "С днём рождения! Счастья, тепла, удачи во всём и побольше приятных сюрпризов!",
        "Поздравляю! Пусть новый год жизни будет ярким, спокойным и счастливым. Здоровья и любви!",
        "С днём рождения! Желаю лёгкости, вдохновения и чтобы каждый день приносил что-то хорошее.",
        "Поздравляю с днём рождения! Оставайся таким же замечательным человеком. Всего самого доброго!",
    )
    private val NEW_YEAR = listOf(
        "С Новым годом! Пусть он будет добрым, щедрым и счастливым. Здоровья и исполнения желаний!",
        "Поздравляю с Новым годом! Тепла, уюта и много радостных моментов в новом году!",
    )
    private val MARCH_8 = listOf(
        "С 8 Марта! Весеннего настроения, красоты, любви и улыбок каждый день!",
        "Поздравляю с Международным женским днём! Пусть рядом будут заботливые люди, а в душе — весна.",
    )
    private val FEB_23 = listOf(
        "С Днём защитника Отечества! Силы, здоровья, мужества и спокойствия!",
        "Поздравляю с 23 Февраля! Крепкого здоровья, удачи и надёжных друзей рядом!",
    )
    private val GENERIC = listOf(
        "Поздравляю! Желаю счастья, здоровья и всего самого хорошего!",
        "От души поздравляю! Пусть всё задуманное сбудется, а настроение будет отличным!",
    )

    fun pick(occasion: String): String {
        val o = occasion.lowercase().replace('ё', 'е')
        val list = when {
            o.isEmpty() -> listOf("Привет! Просто хотела пожелать тебе хорошего дня и отличного настроения!")
            o.contains("рожден") -> BIRTHDAY
            o.contains("новым год") || o.contains("новый год") || o.contains("нг") -> NEW_YEAR
            o.contains("8 марта") || o.contains("восьмым марта") || o.contains("женским") -> MARCH_8
            o.contains("23 февраля") || o.contains("защитник") -> FEB_23
            else -> GENERIC.map { it.replaceFirst("Поздравляю!", "Поздравляю $occasion!").replaceFirst("От души поздравляю!", "От души поздравляю $occasion!") }
        }
        return list.random()
    }
}
